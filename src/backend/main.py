# --- API Endpoints for Submissions ---
@app.post("/submissions/", response_model=SubmissionResponse, status_code=201)
def create_submission(
    db: Session = Depends(get_db),
    photo: UploadFile = File(...),
    participant_id: str = Form(...),
    latitude: str | None = Form(None),
    longitude: str | None = Form(None)
):
    """
    Creates a new submission (e.g., from a bot).
    Accepts multipart/form-data with a photo file and metadata.
    - **RF04**: Upload simultaneous images with metadata (GPS, timestamp).
    - **RF07**: Register each submission (image, class, points, user, team).
    """
    # --- Validation ---
    # 1. Find the participant in the database
    participant = db.query(models.Participant).filter(models.Participant.id == participant_id).first()
    if not participant:
        raise HTTPException(status_code=404, detail=f"Participant with ID '{participant_id}' not found.")
    
    # 2. Get the team_id from the participant
    team_id = participant.team_id

    # --- File Handling ---
    # Generate a unique filename to prevent overwrites
    file_extension = Path(photo.filename).suffix
    unique_filename = f"{uuid.uuid4().hex}{file_extension}"
    file_path = UPLOADS_DIR / unique_filename

    # Save the uploaded file to the local folder
    try:
        with file_path.open("wb") as buffer:
            shutil.copyfileobj(photo.file, buffer)
    except IOError:
        # This will catch file-saving errors, e.g., disk full, permissions
        raise HTTPException(status_code=500, detail="Failed to save the uploaded photo.")
    finally:
        photo.file.close()

    # --- Database Operation ---
    new_submission = models.Submission(
        participant_id=participant_id,
        team_id=team_id, # Use the looked-up team_id
        photo_path=str(file_path), # Store the path as a string
        timestamp=datetime.utcnow(),
        latitude=latitude,
        longitude=longitude,
        status='pending_processing' # Initial status before AI processing
    )
    db.add(new_submission)
    db.commit()
    db.refresh(new_submission)

    # --- Queue Task for Processing ---
    process_submission.delay(new_submission.id)

    return new_submission

